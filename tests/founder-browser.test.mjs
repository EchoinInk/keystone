import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { engineName, founderBrowser, navigateTo } from "./fixtures/browser.mjs";

for (const [device, options] of [
  ["desktop", { viewport: {width:1440,height:900} }],
  ["phone", { viewport: {width:390,height:844}, isMobile:true, hasTouch:true }],
]) test(`founder journeys on ${device} ${engineName} through the built Worker, disposable D1 and private R2`, { timeout: 120000 }, async t => {
  const { mf, db, context, page, url, session, loseAcknowledgement } = await founderBrowser(t, options);
  const errors = [];
  page.on("pageerror", reason => errors.push(reason.message));
  const nav = name => navigateTo(page, name, options.hasTouch);
  const tab = name => page.locator(".manager-tabs button").filter({hasText:name}).click();
  const dialog = page.getByRole("dialog");
  const close = () => dialog.getByRole("button",{name:"Close",exact:true}).click();
  const button = (host,name) => host.getByRole("button",{name});
  const record = name => page.locator(".record-main").filter({hasText:name}).click();
  const postResponse = () => page.waitForResponse(r => r.request().method()==="POST" && new URL(r.url()).pathname==="/api/data");
  async function mutate(action,status=200) {
    const [res] = await Promise.all([postResponse(),action()]);
    const result = await res.json();
    assert.equal(res.status(),status,result.error);
    return result;
  }
  const save = async () => {
    const result = await mutate(()=>button(dialog,/Save record/).click());
    await dialog.waitFor({state:"hidden"});
    return result;
  };
  const add = () => button(page,/＋ Add record/).click();
  const reload = async view => { await page.reload(); await nav(view); };
  await page.goto(url);
  await page.getByRole("heading",{name:"Mission Control",exact:true}).waitFor();

  await t.test("create and manage sprint work and weekly objectives across reloads",async () => {
    await nav("Sprints"); await button(page,/New sprint/).click();
    await dialog.getByLabel("Sprint name",{exact:true}).fill("Delivery week");
    await dialog.getByLabel("Goal",{exact:true}).fill("Deliver the brief");
    await dialog.getByLabel("Duration",{exact:true}).selectOption("Custom");
    await dialog.getByLabel("Start date",{exact:true}).fill("2026-11-19");
    await dialog.getByLabel("Ends",{exact:true}).fill("2026-11-27");
    const sprint = (await save()).recordId;
    await nav("Freelance Launch"); await button(page,/^Add objective/).click();
    await dialog.getByLabel("Objective",{exact:true}).fill("Deliver onboarding");
    const weekly = (await save()).recordId;
    const card = page.locator(".objective-card").filter({hasText:"Deliver onboarding"});
    await card.locator(":scope > summary").click(); await button(card,/＋ Add task/).click();
    assert.equal(await dialog.getByLabel("Sprint",{exact:true}).inputValue(),sprint);
    assert.equal(await dialog.getByLabel("Freelance Launch objective",{exact:true}).inputValue(),weekly);
    await dialog.getByLabel("Task",{exact:true}).fill("Review brief");
    await dialog.getByLabel("Status",{exact:true}).selectOption("In progress");
    const task = (await save()).recordId;
    await reload("Sprints"); await tab("Sprint objectives"); await add();
    await dialog.getByLabel("Daily objective",{exact:true}).fill("Brief review");
    await dialog.getByLabel(/Connected task/).selectOption(task);
    const daily = (await save()).recordId;
    await reload("Tasks");
    await mutate(()=>button(page,"Complete Review brief").click());
    await reload("Freelance Launch");
    assert.match(await card.locator(":scope > summary").innerText(),/1\/1 complete/);
    await card.locator(":scope > summary").click(); await button(card,/Edit objective/).click();
    await dialog.getByLabel("Outcome",{exact:true}).fill("Ready for delivery"); await save();
    await reload("Sprints");
    assert.match(await page.locator(".sprint-progress").innerText(),/100% complete · 1 of 1/);
    await tab("Sprint objectives"); await record("Brief review");
    assert.equal(await dialog.getByLabel(/Status · from linked tasks/).inputValue(),"Completed");
    await close(); await reload("Tasks");
    const reopened = await mutate(()=>button(page,"Reopen Review brief").click());
    assert.equal(reopened.data.tasks.find(r=>r.id===task).status,"In progress");
    assert.equal(reopened.data.sprintObjectives.find(r=>r.id===daily).status,"In progress");
    await page.getByLabel("Filter by status").selectOption("Active");
    await mutate(()=>page.getByLabel("Status for Review brief").selectOption("Cancelled"));
    await page.getByLabel("Filter by status").selectOption("Cancelled");
    await record("Review brief");
    const secondTab = await context.newPage();
    await secondTab.goto(url);
    await navigateTo(secondTab, "Tasks", options.hasTouch);
    await secondTab.locator(".record-main").filter({hasText:"Review brief"}).click();
    const otherEditor = secondTab.getByRole("dialog");
    await otherEditor.getByLabel("Task",{exact:true}).fill("Reviewed brief");
    await button(otherEditor,/Save record/).click();
    await otherEditor.waitFor({state:"hidden"});
    await secondTab.close();
    await dialog.getByRole("textbox",{name:"Notes",exact:true}).fill("Founder feedback");
    await mutate(()=>button(dialog,/Save record/).click(),409);
    await dialog.getByRole("alert").waitFor();
    assert.equal(await dialog.getByRole("textbox",{name:"Notes",exact:true}).inputValue(),"Founder feedback");
    await button(dialog,"Reopen latest version").click();
    assert.equal(await dialog.getByLabel("Task",{exact:true}).inputValue(),"Reviewed brief");
    await dialog.getByRole("textbox",{name:"Notes",exact:true}).fill("Reviewed together"); await save();
    await tab("Founder goals"); await add();
    await dialog.getByLabel("Goal",{exact:true}).fill("Deliver the pilot"); await save();
    await record("Deliver the pilot");
    await dialog.getByLabel("Progress %").fill("100");
    await dialog.getByLabel("Status",{exact:true}).selectOption("Complete");
    await save(); await reload("Tasks"); await tab("Founder goals");
    assert.match(await page.locator(".data-row").filter({hasText:"Deliver the pilot"}).innerText(),/100%/);
  });

  await t.test("advance a lead and open its onboarding client and project",async () => {
    await reload("Clients"); await add();
    await dialog.getByLabel("Contact name").fill("Ari Test");
    await dialog.getByLabel("Company",{exact:true}).fill("Fixture studio");
    await dialog.getByLabel("Lead status",{exact:true}).selectOption("Qualified");
    await save(); await record("Ari Test");
    assert.equal(await button(dialog,"Convert lead").count(),0);
    await button(dialog,"Add proposal").click();
    await dialog.getByLabel("Proposal title").fill("Ari proposal"); await save();
    await record("Ari Test");
    await dialog.getByLabel("Lead status",{exact:true}).selectOption("Won"); await save();
    await record("Ari Test"); await mutate(()=>button(dialog,"Convert lead").click());
    await button(dialog,/Open client · Ari Test/).click();
    assert.equal(await dialog.getByLabel("Status",{exact:true}).inputValue(),"Onboarding");
    await button(dialog,/Open proposal · Ari proposal/).click();
    assert.equal(await dialog.getByLabel("Client",{exact:true}).locator("option:checked").innerText(),"Ari Test");
    await close(); await record("Ari Test"); await button(dialog,/Open client · Ari Test/).click();
    await button(dialog,"Add project").click();
    await dialog.getByLabel("Project",{exact:true}).fill("Ari delivery"); await save();
    await reload("Clients"); await record("Ari Test"); await button(dialog,/Open client · Ari Test/).click();
    await button(dialog,/Open project · Ari delivery/).click();
    assert.equal(await dialog.getByLabel("Client",{exact:true}).locator("option:checked").innerText(),"Ari Test"); await close();
  });

  await t.test("recover an upload, open and edit text, download and delete with admission checks",async () => {
    await reload("Knowledge Base"); await tab("Documents"); await add();
    await dialog.getByLabel(/Document name/).fill("Brief.md");
    await dialog.locator('input[type="file"]').setInputFiles({name:"source.md",mimeType:"text/markdown",buffer:Buffer.from("# First draft")});
    loseAcknowledgement();
    await button(dialog,/Save record/).click(); await dialog.getByRole("alert").waitFor();
    const upload = await save();
    assert.equal(upload.data.documents.length,1);
    const id = upload.recordId;
    const originalKey = upload.data.documents[0].objectKey;
    await reload("Knowledge Base"); await tab("Documents"); await record("Brief.md");
    await dialog.getByLabel(/Document name/).fill("Delivery.md"); const renamed = await save();
    assert.equal(renamed.data.documents[0].objectKey,originalKey);
    const row = page.locator(".data-row").filter({hasText:"Delivery.md"});
    const [preview] = await Promise.all([context.waitForEvent("page"),row.getByRole("link",{name:"Open document"}).click()]);
    await preview.waitForLoadState(); assert.equal(await preview.locator("body").innerText(),"# First draft"); await preview.close();
    await record("Delivery.md"); await button(dialog,"Edit text").click();
    await dialog.getByLabel("Document text").fill("# Approved\nSecond line");
    const edited = await save(); assert.equal(edited.recordId,id);
    const bucket = await mf.getR2Bucket("BUCKET","site");
    assert.notEqual(edited.data.documents[0].objectKey,originalKey);
    assert.equal(edited.cleanup.pending,0,"R2 replacement cleanup should finish in the disposable binding");
    assert.equal(await bucket.head(originalKey),null,"Replaced bytes must be removed after their final reference");
    await reload("Knowledge Base"); await tab("Documents");
    const [download] = await Promise.all([page.waitForEvent("download"),row.getByRole("button",{name:"Download",exact:true}).click()]);
    assert.equal(download.suggestedFilename(),"Delivery.md");
    assert.equal(await readFile(await download.path(),"utf8"),"# Approved\nSecond line");
    await record("Delivery.md");
    await dialog.getByLabel(/Replace attachment/).setInputFiles({name:"approved.bin",mimeType:"application/octet-stream",buffer:Buffer.from([0,128,255])});
    const replaced = await save();
    assert.equal(await row.getByRole("link",{name:"Open document"}).count(),0);
    await record("Delivery.md");
    assert.equal(await button(dialog,"Edit text").count(),0);
    page.once("dialog",confirmation=>confirmation.dismiss()); await button(dialog,"Delete record").click();
    await dialog.waitFor(); assert.equal(await db.prepare("SELECT COUNT(*) n FROM documents").first("n"),1);
    await session("other");
    page.once("dialog",confirmation=>confirmation.accept());
    await mutate(()=>button(dialog,"Delete record").click(),403);
    assert.equal(await db.prepare("SELECT COUNT(*) n FROM documents").first("n"),1);
    const denied = await page.goto(url+"/api/files?id="+id+"&open=1"); assert.equal(denied.status(),403);
    await session("founder"); await page.goto(url); await nav("Knowledge Base"); await tab("Documents");
    await record("Delivery.md"); page.once("dialog",confirmation=>confirmation.accept());
    await mutate(()=>button(dialog,"Delete record").click());
    await reload("Knowledge Base"); await tab("Documents"); assert.equal(await row.count(),0);
    assert.equal((await page.goto(url+"/api/files?id="+id)).status(),404);
    assert.equal(await bucket.head(replaced.data.documents[0].objectKey),null,"Deleted bytes must be removed after their final reference");
  });

  assert.deepEqual(errors,[]);
});
